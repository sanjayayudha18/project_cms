-- 030_vault_allocation.sql
-- Pemenuhan vault ACM: bagi nominal request ke vault + tiket pemenuhan vault
-- (.claude/sdlc/cit-vault-select/spec.md v3 + plan.md S1, accepted 2026-10-13).
--
--   * acm_area_regions: region_code -> Area ACM (FR1). Menggantikan acm_area_branches untuk rencana baru.
--   * vendor_request_vault_plans: buffer_reason (FR4.3) + maksimal satu rencana bukan cancelled per request (FR2.2).
--   * vendor_request_vault_allocations (+ _amounts): baris vault per rencana + nominal per denom (FR4).
--   * vendor_request_vault_tickets: tiket pemenuhan vault per (request, vault) (FR6).
--   * vendor_request_vault_assignments (027, per ATM) tidak ditulis lagi; tidak dihapus.
--
-- SAFETY (Sec 4 #7): additive. Unik parsial plan aman di dev (0 request dengan >1 plan aktif, dicek 2026-10-13).
-- Satu tx. Forward-only: no down migration (project convention).
BEGIN;

-- 1. Area ACM per region (FR1). Link table murni, seperti acm_area_branches; perubahan diaudit di service.
CREATE TABLE public.acm_area_regions (
    acm_area_id bigint NOT NULL REFERENCES public.acm_areas(id),
    region_code text   NOT NULL CONSTRAINT acm_area_regions_region_code_chk CHECK (region_code ~ '^[A-Z0-9]{2,10}$'),
    created_by  bigint NOT NULL REFERENCES public.users(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (acm_area_id, region_code),
    CONSTRAINT acm_area_regions_region_uq UNIQUE (region_code)
);

-- 2. Rencana: satu per request (FR2.2) + alasan buffer (FR4.3, V13)
ALTER TABLE public.vendor_request_vault_plans
    ADD COLUMN buffer_reason text
        CONSTRAINT vendor_request_vault_plans_buffer_reason_chk CHECK (char_length(buffer_reason) BETWEEN 10 AND 500);
-- FR2.2: at most one live plan per request.
CREATE UNIQUE INDEX vendor_request_vault_plans_live_uq
    ON public.vendor_request_vault_plans (vendor_request_id) WHERE status <> 'cancelled';

-- 3. Target FK komposit: vault milik branch
ALTER TABLE public.vendor_vaults
    ADD CONSTRAINT vendor_vaults_id_branch_uq UNIQUE (id, vendor_branch_id);

-- 4. Alokasi vault per rencana (FR4). Replace-all saat draft (hard delete terdokumentasi, seperti assignments 027).
CREATE TABLE public.vendor_request_vault_allocations (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vault_plan_id     bigint NOT NULL REFERENCES public.vendor_request_vault_plans(id),
    vendor_request_id bigint NOT NULL REFERENCES public.vendor_requests(id),
    vendor_vault_id   bigint NOT NULL,
    vault_branch_id   bigint NOT NULL,
    tier              smallint NOT NULL CONSTRAINT vendor_request_vault_allocations_tier_chk CHECK (tier BETWEEN 1 AND 3),
    is_urgent         boolean NOT NULL DEFAULT false,
    urgent_reason     text,
    saldo_snapshot    jsonb,
    capacity_snapshot jsonb,
    capacity_warning  boolean NOT NULL DEFAULT false,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT vendor_request_vault_allocations_vault_fk
        FOREIGN KEY (vendor_vault_id, vault_branch_id) REFERENCES public.vendor_vaults (id, vendor_branch_id),
    CONSTRAINT vendor_request_vault_allocations_vault_uq UNIQUE (vault_plan_id, vendor_vault_id),
    CONSTRAINT vendor_request_vault_allocations_urgent_chk CHECK (
        (NOT is_urgent AND urgent_reason IS NULL)
        OR (is_urgent AND char_length(urgent_reason) BETWEEN 10 AND 500)),
    CONSTRAINT vendor_request_vault_allocations_tier3_chk CHECK (tier < 3 OR is_urgent)
);
CREATE INDEX vendor_request_vault_allocations_vault_idx ON public.vendor_request_vault_allocations (vendor_vault_id);
CREATE INDEX vendor_request_vault_allocations_request_idx ON public.vendor_request_vault_allocations (vendor_request_id);
CREATE TRIGGER trg_vendor_request_vault_allocations_set_updated_at BEFORE UPDATE ON public.vendor_request_vault_allocations
    FOR EACH ROW WHEN (old.* IS DISTINCT FROM new.*) EXECUTE FUNCTION public.set_updated_at();
COMMENT ON COLUMN public.vendor_request_vault_allocations.saldo_snapshot IS
    'Saldo vault per denom saat disimpan/submit, {"100000": "123000000", ...}; null = tidak diketahui.';
COMMENT ON COLUMN public.vendor_request_vault_allocations.capacity_snapshot IS
    'Sisa kapasitas vault per denom (saldo - alokasi rencana lain) saat disimpan/submit; null = tidak diketahui.';

-- Nominal per denom (FR4.2, V12): > 0 dan kelipatan pecahan, full IDR (bigint, tidak pernah float).
CREATE TABLE public.vendor_request_vault_allocation_amounts (
    allocation_id bigint  NOT NULL REFERENCES public.vendor_request_vault_allocations(id) ON DELETE CASCADE,
    denom         integer NOT NULL CONSTRAINT vendor_request_vault_allocation_amounts_denom_chk
                      CHECK (denom IN (100000, 50000, 20000, 10000, 5000, 2000, 1000)),
    amount        bigint  NOT NULL CONSTRAINT vendor_request_vault_allocation_amounts_amount_chk
                      CHECK (amount > 0 AND amount % denom = 0),
    PRIMARY KEY (allocation_id, denom)
);

-- 5. Tiket pemenuhan vault per (request, vault) (FR6). Nomor <vault_code>_<YYYYMMDD>_<NNN>, NNN global per
-- (vault, tanggal replenish), tidak pernah dipakai ulang; satu baris per pasangan sepanjang masa (reaktivasi = nomor sama).
CREATE TABLE public.vendor_request_vault_tickets (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_request_id bigint NOT NULL REFERENCES public.vendor_requests(id),
    vendor_vault_id   bigint NOT NULL REFERENCES public.vendor_vaults(id),
    replenish_date    date NOT NULL,
    seq               smallint NOT NULL CONSTRAINT vendor_request_vault_tickets_seq_chk CHECK (seq BETWEEN 1 AND 999),
    ticket_number     text NOT NULL,
    is_active         boolean NOT NULL DEFAULT true,
    created_at        timestamptz NOT NULL DEFAULT now(),
    deactivated_at    timestamptz,
    CONSTRAINT vendor_request_vault_tickets_number_uq UNIQUE (ticket_number),
    CONSTRAINT vendor_request_vault_tickets_seq_uq UNIQUE (vendor_vault_id, replenish_date, seq),
    CONSTRAINT vendor_request_vault_tickets_pair_uq UNIQUE (vendor_request_id, vendor_vault_id),
    CONSTRAINT vendor_request_vault_tickets_inactive_chk CHECK (is_active OR deactivated_at IS NOT NULL)
);

COMMENT ON TABLE public.vendor_request_vault_assignments IS
    'Penetapan branch vault per ATM (027). Tidak ditulis lagi sejak 030 — diganti vendor_request_vault_allocations.';

COMMIT;
