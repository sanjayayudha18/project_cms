-- 031_replenish_realization.sql
-- Realisasi pengisian ATM vs order (.claude/sdlc/replenishment-realisasi/spec.md + plan.md S1, accepted 2026-10-14).
--
--   * holidays: kalender hari libur untuk hitung hari kerja (FR1). ADMIN, langsung berlaku + audit (deviasi GR#3).
--   * vendor_request_realizations (+ _amounts): laporan realisasi vendor per tiket replenish (FR2).
--   * replenish_classifications (+ _amounts): hasil klasifikasi harian per tiket / pengisian tanpa order (FR3),
--     ditulis job Python replenish_classify. Input (order, ITM, laporan vendor) + selisih disimpan (Sec 6).
--
-- Nominal: bigint full IDR (pola 030 vendor_request_vault_allocation_amounts), tidak pernah float.
-- SAFETY (Sec 4 #7): additive, tabel lama tidak diubah. Satu tx. Forward-only: no down migration.
BEGIN;

-- 1. Hari libur (FR1). Soft-disable via is_active/deleted_at; tanggal unik di antara baris aktif.
CREATE TABLE public.holidays (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holiday_date date   NOT NULL,
    name         text   NOT NULL CONSTRAINT holidays_name_chk CHECK (char_length(btrim(name)) BETWEEN 1 AND 100),
    is_active    boolean NOT NULL DEFAULT true,
    created_by   bigint NOT NULL REFERENCES public.users(id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    deleted_at   timestamptz,
    CONSTRAINT holidays_active_chk CHECK (is_active = (deleted_at IS NULL))
);
CREATE UNIQUE INDEX holidays_active_date_uq ON public.holidays (holiday_date) WHERE is_active;
CREATE TRIGGER trg_holidays_set_updated_at BEFORE UPDATE ON public.holidays
    FOR EACH ROW WHEN (old.* IS DISTINCT FROM new.*) EXECUTE FUNCTION public.set_updated_at();

-- 2. Laporan realisasi vendor per tiket replenish (FR2). Satu per tiket; resubmit menimpa (riwayat di audit_logs).
--    realized_date NULL = ATM gagal diisi (vendor_request_tickets.result = 'failed').
CREATE TABLE public.vendor_request_realizations (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id         bigint NOT NULL REFERENCES public.vendor_request_tickets(id),
    vendor_request_id bigint NOT NULL REFERENCES public.vendor_requests(id),
    realized_date     date,
    submitted_by      bigint NOT NULL REFERENCES public.users(id),
    submitted_at      timestamptz NOT NULL DEFAULT now(),
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT vendor_request_realizations_ticket_uq UNIQUE (ticket_id)
);
CREATE INDEX vendor_request_realizations_request_idx ON public.vendor_request_realizations (vendor_request_id);
CREATE TRIGGER trg_vendor_request_realizations_set_updated_at BEFORE UPDATE ON public.vendor_request_realizations
    FOR EACH ROW WHEN (old.* IS DISTINCT FROM new.*) EXECUTE FUNCTION public.set_updated_at();

-- Nominal per denom (FR2.2): >= 0, kelipatan pecahan. Replace-all saat resubmit (hard delete baris anak
-- terdokumentasi, seperti 030 allocation amounts); kosong untuk tiket failed.
CREATE TABLE public.vendor_request_realization_amounts (
    realization_id bigint  NOT NULL REFERENCES public.vendor_request_realizations(id) ON DELETE CASCADE,
    denom          integer NOT NULL CONSTRAINT vendor_request_realization_amounts_denom_chk
                       CHECK (denom IN (100000, 50000, 20000, 10000, 5000, 2000, 1000)),
    amount         bigint  NOT NULL CONSTRAINT vendor_request_realization_amounts_amount_chk
                       CHECK (amount >= 0 AND amount % denom = 0),
    PRIMARY KEY (realization_id, denom)
);

-- 3. Hasil klasifikasi (FR3). Satu baris per tiket replenish, atau per baris itm_replenish tanpa tiket (no_order).
--    itm_replenish_id ON DELETE SET NULL: ETL ITM menghapus baris file yang diproses ulang; realized_* menyimpan
--    snapshot, baris belum final dihitung ulang job berikutnya.
CREATE TABLE public.replenish_classifications (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id          bigint REFERENCES public.vendor_request_tickets(id),
    itm_replenish_id   bigint REFERENCES public.itm_replenish(id) ON DELETE SET NULL,
    terminal_id        text   NOT NULL,
    vendor_id          bigint REFERENCES public.vendors(id),
    vendor_branch_id   bigint REFERENCES public.vendor_branches(id),
    scheduled_date     date,
    realized_date      date,
    realized_time      time,
    report_date        date GENERATED ALWAYS AS (COALESCE(scheduled_date, realized_date)) STORED,
    workday_offset     smallint,
    classification     text   NOT NULL CONSTRAINT replenish_classifications_class_chk CHECK (classification IN
                           ('pending', 'on_schedule', 'early', 'late', 'not_done', 'no_order', 'void')),
    is_final           boolean NOT NULL DEFAULT false,
    has_amount_diff    boolean NOT NULL DEFAULT false,
    vendor_mismatch    boolean NOT NULL DEFAULT false,
    vendor_report_late boolean NOT NULL DEFAULT false,
    late_notified_at   timestamptz,
    classified_at      timestamptz NOT NULL DEFAULT now(),
    finalized_at       timestamptz,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT replenish_classifications_ticket_uq UNIQUE (ticket_id),
    CONSTRAINT replenish_classifications_itm_uq UNIQUE (itm_replenish_id),
    -- no_order <=> tidak ada tiket; selain itu wajib tiket + jadwal
    CONSTRAINT replenish_classifications_source_chk CHECK (
        (classification = 'no_order' AND ticket_id IS NULL AND realized_date IS NOT NULL)
        OR (classification <> 'no_order' AND ticket_id IS NOT NULL AND scheduled_date IS NOT NULL)),
    CONSTRAINT replenish_classifications_final_chk CHECK (
        (classification = 'pending') = (NOT is_final) AND is_final = (finalized_at IS NOT NULL)),
    CONSTRAINT replenish_classifications_offset_chk CHECK (
        workday_offset IS NULL OR workday_offset BETWEEN -2 AND 2)
);
CREATE INDEX replenish_classifications_report_date_idx ON public.replenish_classifications (report_date);
CREATE INDEX replenish_classifications_vendor_date_idx ON public.replenish_classifications (vendor_id, report_date);
CREATE INDEX replenish_classifications_open_idx ON public.replenish_classifications (id) WHERE NOT is_final;
-- Tanpa WHEN (old.* IS DISTINCT FROM new.*): Postgres menolak whole-row reference pada tabel dengan kolom generated.
CREATE TRIGGER trg_replenish_classifications_set_updated_at BEFORE UPDATE ON public.replenish_classifications
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
COMMENT ON TABLE public.replenish_classifications IS
    'Klasifikasi realisasi vs order per tiket replenish (atau no_order per baris ITM). Ditulis job Python replenish_classify; final tidak dihitung ulang.';

-- Nominal per denom (FR3.6): order vs ITM vs laporan vendor, selisih = ITM - order.
CREATE TABLE public.replenish_classification_amounts (
    classification_id bigint  NOT NULL REFERENCES public.replenish_classifications(id) ON DELETE CASCADE,
    denom             integer NOT NULL CONSTRAINT replenish_classification_amounts_denom_chk
                          CHECK (denom IN (100000, 50000, 20000, 10000, 5000, 2000, 1000)),
    order_amount      bigint  NOT NULL DEFAULT 0 CHECK (order_amount >= 0),
    itm_amount        bigint  NOT NULL DEFAULT 0 CHECK (itm_amount >= 0),
    vendor_amount     bigint  CHECK (vendor_amount >= 0),
    diff              bigint  GENERATED ALWAYS AS (itm_amount - order_amount) STORED,
    PRIMARY KEY (classification_id, denom)
);

COMMIT;
