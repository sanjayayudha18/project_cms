-- 1. Peran + menu + hak menu ------------------------------------------------------------------------------------------
INSERT INTO public.roles (role, description) VALUES
    ('CC-CWM',         'Tim CWM — parameter cash count, area, mapping PIC, review jadwal (cash count)'),
    ('CC-COORDINATOR', 'PIC Coordinator cash count per region'),
    ('CC-EXECUTOR',    'PIC Executor cash count per area'),
    ('CC-CCR',         'Cash Count & Resolution (= Cash Control & Resolution) — kategori anomaly, checklist BA'),
    ('CC-RECON',       'Tim rekonsiliasi hasil cash count'),
    ('CC-D3',          'Approver cash count tingkat D3'),
    ('CC-D2',          'Approver cash count tingkat D2')
ON CONFLICT (role) DO NOTHING;

INSERT INTO public.menu_features (parent_id, key, label, kind, sort_order)
SELECT id, 'cash-count.parameters', 'Parameter Cash Count', 'feature', 0 FROM public.menu_features WHERE key = 'cash-count'
ON CONFLICT (key) DO NOTHING;
INSERT INTO public.menu_features (parent_id, key, label, kind, sort_order)
SELECT id, 'cash-count.pic-mapping', 'Mapping PIC', 'feature', 1 FROM public.menu_features WHERE key = 'cash-count'
ON CONFLICT (key) DO NOTHING;

INSERT INTO public.role_permissions (role_id, menu_feature_id, granted_by)
SELECT r.id, mf.id, (SELECT u.id FROM public.users u JOIN public.roles ar ON ar.id = u.role_id
                     WHERE ar.role = 'ADMIN' ORDER BY u.id LIMIT 1)
FROM public.roles r
JOIN public.menu_features mf ON mf.key = ANY (CASE r.role
        WHEN 'ADMIN'  THEN ARRAY['cash-count', 'cash-count.parameters', 'cash-count.pic-mapping']
        WHEN 'CC-CWM' THEN ARRAY['cash-count', 'cash-count.parameters', 'cash-count.pic-mapping']
        WHEN 'CC-CCR' THEN ARRAY['cash-count', 'cash-count.parameters']
        ELSE ARRAY['cash-count']
    END)
WHERE r.role IN ('ADMIN', 'CC-CWM', 'CC-COORDINATOR', 'CC-EXECUTOR', 'CC-CCR', 'CC-RECON', 'CC-D3', 'CC-D2')
ON CONFLICT (role_id, menu_feature_id) DO NOTHING;

-- 2. Parameter kategori vault (satu baris = satu set) -----------------------------------------------------------------
CREATE TABLE public.cash_count_category_params (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medium_min_amount numeric(20,2) NOT NULL CONSTRAINT cash_count_category_params_min_chk CHECK (medium_min_amount > 0),
    medium_max_amount numeric(20,2) NOT NULL,
    currency_code     character(3)  NOT NULL DEFAULT 'IDR' CONSTRAINT cash_count_category_params_currency_chk CHECK (currency_code = 'IDR'),
    onsite_high       smallint NOT NULL CONSTRAINT cash_count_category_params_onsite_high_chk   CHECK (onsite_high   BETWEEN 0 AND 6),
    onsite_medium     smallint NOT NULL CONSTRAINT cash_count_category_params_onsite_medium_chk CHECK (onsite_medium BETWEEN 0 AND 6),
    onsite_low        smallint NOT NULL CONSTRAINT cash_count_category_params_onsite_low_chk    CHECK (onsite_low    BETWEEN 0 AND 6),
    period_months     smallint NOT NULL DEFAULT 6 CONSTRAINT cash_count_category_params_period_chk CHECK (period_months = 6),
    created_by        bigint NOT NULL REFERENCES public.users(id),
    effective_from    timestamptz NOT NULL DEFAULT now(),
    superseded_at     timestamptz,
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT cash_count_category_params_range_chk CHECK (medium_min_amount < medium_max_amount),
    CONSTRAINT cash_count_category_params_superseded_chk CHECK (superseded_at IS NULL OR superseded_at >= effective_from)
);
-- Tepat satu set aktif (AC-5.1-04): applier menutup set lama lalu insert set baru dalam satu tx.
CREATE UNIQUE INDEX cash_count_category_params_active_uq
    ON public.cash_count_category_params ((true)) WHERE superseded_at IS NULL;
CREATE INDEX cash_count_category_params_created_by_idx ON public.cash_count_category_params (created_by);
COMMENT ON TABLE public.cash_count_category_params IS
    'Set ambang kategori vault H/M/L cash count (5.1). saldo < medium_min -> LOW; medium_min <= saldo <= medium_max -> MEDIUM; saldo > medium_max -> HIGH. onsite_* = kunjungan onsite per period_months (6). Berversi: superseded_at NULL = set aktif. Migrasi 041.';

INSERT INTO public.cash_count_category_params
    (medium_min_amount, medium_max_amount, onsite_high, onsite_medium, onsite_low, created_by)
SELECT 5000000000.00, 15000000000.00, 3, 2, 1,
       (SELECT u.id FROM public.users u JOIN public.roles ar ON ar.id = u.role_id
        WHERE ar.role = 'ADMIN' ORDER BY u.id LIMIT 1);

-- 3. Kategori ATM Anomaly ---------------------------------------------------------------------------------------------
CREATE TABLE public.cash_count_anomaly_categories (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text NOT NULL CONSTRAINT cash_count_anomaly_categories_code_uq UNIQUE
                     CONSTRAINT cash_count_anomaly_categories_code_chk CHECK (code ~ '^[A-Z0-9_]{2,20}$'),
    name        text NOT NULL CONSTRAINT cash_count_anomaly_categories_name_chk
                     CHECK (name = btrim(name) AND char_length(name) BETWEEN 1 AND 100),
    description text CONSTRAINT cash_count_anomaly_categories_description_chk CHECK (char_length(description) <= 500),
    is_active   boolean NOT NULL DEFAULT true,
    deleted_at  timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_cash_count_anomaly_categories_set_updated_at BEFORE UPDATE ON public.cash_count_anomaly_categories
    FOR EACH ROW WHEN (old.* IS DISTINCT FROM new.*) EXECUTE FUNCTION public.set_updated_at();

-- 4. Item checklist Berita Acara (tanpa seed, K15) --------------------------------------------------------------------
CREATE TABLE public.cash_count_checklist_items (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category   text NOT NULL CONSTRAINT cash_count_checklist_items_category_chk
                    CHECK (category IN ('SELECTED_MACHINE', 'NON_MACHINE')),
    day        text CONSTRAINT cash_count_checklist_items_day_chk CHECK (day IN ('DAY1', 'DAY2')),
    point_no   smallint NOT NULL CONSTRAINT cash_count_checklist_items_point_no_chk CHECK (point_no > 0),
    item_text  text NOT NULL CONSTRAINT cash_count_checklist_items_text_chk
                    CHECK (item_text = btrim(item_text) AND char_length(item_text) BETWEEN 1 AND 500),
    is_active  boolean NOT NULL DEFAULT true,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    -- Hari wajib untuk SELECTED_MACHINE (DAY1 mesin / DAY2 vault), tidak boleh untuk NON_MACHINE.
    CONSTRAINT cash_count_checklist_items_day_required_chk CHECK ((category = 'SELECTED_MACHINE') = (day IS NOT NULL))
);
CREATE UNIQUE INDEX cash_count_checklist_items_point_active_uq
    ON public.cash_count_checklist_items (category, COALESCE(day, ''), point_no) WHERE is_active;
CREATE TRIGGER trg_cash_count_checklist_items_set_updated_at BEFORE UPDATE ON public.cash_count_checklist_items
    FOR EACH ROW WHEN (old.* IS DISTINCT FROM new.*) EXECUTE FUNCTION public.set_updated_at();

-- 5. Area cash count --------------------------------------------------------------------------------------------------
CREATE TABLE public.cash_count_areas (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       text NOT NULL CONSTRAINT cash_count_areas_code_uq UNIQUE
                    CONSTRAINT cash_count_areas_code_chk CHECK (code ~ '^[A-Z0-9_]{2,20}$'),
    name       text NOT NULL CONSTRAINT cash_count_areas_name_chk
                    CHECK (name = btrim(name) AND char_length(name) BETWEEN 1 AND 100),
    is_active  boolean NOT NULL DEFAULT true,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_cash_count_areas_set_updated_at BEFORE UPDATE ON public.cash_count_areas
    FOR EACH ROW WHEN (old.* IS DISTINCT FROM new.*) EXECUTE FUNCTION public.set_updated_at();

-- 6. Region per area (link table murni; ditulis ulang oleh applier area, perubahan diaudit di service) ----------------
-- PK region_code = satu region satu area. region_code = vendor_branches.region_code (bukan regions); keberadaan di
-- vendor_branches aktif dicek di service (kolom itu tidak unik, jadi tanpa FK).
CREATE TABLE public.cash_count_area_regions (
    region_code text   NOT NULL PRIMARY KEY CONSTRAINT cash_count_area_regions_region_code_chk CHECK (region_code ~ '^[A-Z0-9]{2,10}$'),
    area_id     bigint NOT NULL REFERENCES public.cash_count_areas(id),
    created_by  bigint NOT NULL REFERENCES public.users(id),
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX cash_count_area_regions_area_idx ON public.cash_count_area_regions (area_id);

-- 7. Mapping PIC ------------------------------------------------------------------------------------------------------
-- Syarat user (aktif, auth_source = 'ldap', peran CC-COORDINATOR/CC-EXECUTOR) dijaga di service submit + applier.
CREATE TABLE public.cash_count_pics (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pic_role    text   NOT NULL CONSTRAINT cash_count_pics_pic_role_chk CHECK (pic_role IN ('COORDINATOR', 'EXECUTOR')),
    user_id     bigint NOT NULL REFERENCES public.users(id),
    region_code text   CONSTRAINT cash_count_pics_region_code_chk CHECK (region_code ~ '^[A-Z0-9]{2,10}$'),
    area_id     bigint REFERENCES public.cash_count_areas(id),
    is_active   boolean NOT NULL DEFAULT true,
    deleted_at  timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT cash_count_pics_scope_chk CHECK (
           (pic_role = 'COORDINATOR' AND region_code IS NOT NULL AND area_id IS NULL)
        OR (pic_role = 'EXECUTOR'    AND area_id IS NOT NULL     AND region_code IS NULL))
);
CREATE UNIQUE INDEX cash_count_pics_active_uq
    ON public.cash_count_pics (pic_role, user_id, COALESCE(region_code, ''), COALESCE(area_id, 0)) WHERE is_active;
CREATE INDEX cash_count_pics_user_idx ON public.cash_count_pics (user_id);
CREATE INDEX cash_count_pics_area_idx ON public.cash_count_pics (area_id) WHERE area_id IS NOT NULL;
CREATE TRIGGER trg_cash_count_pics_set_updated_at BEFORE UPDATE ON public.cash_count_pics
    FOR EACH ROW WHEN (old.* IS DISTINCT FROM new.*) EXECUTE FUNCTION public.set_updated_at();

-- 8. Kind ekspor 'cash_count_pics' (master-data kind: status_filter wajib, global tanpa vendor) ------------------------
ALTER TABLE public.export_jobs DROP CONSTRAINT export_jobs_kind_chk;
ALTER TABLE public.export_jobs ADD CONSTRAINT export_jobs_kind_chk CHECK (kind IN (
