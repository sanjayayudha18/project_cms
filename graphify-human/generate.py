@dataclass
class Endpoint:
    module: str
    method: str
    path: str
    roles: list[str]
    handler: str
    files: set[str]

    @property
    def key(self) -> tuple[str, str]:
        return self.method, norm_path(self.path)


CHI_CALL_RE = re.compile(r"\.(Get|Post|Put|Patch|Delete|Mount|Route|Group|Use)\(")


class GoModule:
    def __init__(self, name: str, main_rel: str, handler_dir: str, role_vars: dict[str, list[str]]):
        self.name = name
        self.main = main_rel
        self.role_vars = role_vars
        self.ctor_type: dict[str, str] = {}
        self.method_file: dict[tuple[str, str], str] = {}
        self.endpoints: list[Endpoint] = []
        for f in files_under(handler_dir, ".go"):
            text = read(f)
            for m in re.finditer(r"func\s+(New\w+)\s*\(", text):
                close = match_forward(text, m.end() - 1)
                rt = re.match(r"\s*\(?\s*\*?(\w+)", text[close + 1:])
                if rt:
                    self.ctor_type[m.group(1)] = rt.group(1)
            for m in re.finditer(r"func\s*\(\s*\w+\s+\*?(\w+)\s*\)\s*(\w+)\s*\(", text):
                self.method_file.setdefault((m.group(1), m.group(2)), f)

    def parse(self) -> list[Endpoint]:
        text = read(self.main)
        if text:
            self.parse_block(text, self.main, 0, len(text), "", [], None, 0)
        return self.endpoints

    def var_type(self, var: str, text: str) -> str | None:
        m = re.search(rf"\b{re.escape(var)}\s*:?=\s*handler\.(New\w+)\s*\(", text)
        if m:
            return self.ctor_type.get(m.group(1), m.group(1)[3:])
        m = re.search(rf"\b{re.escape(var)}\s+\*handler\.(\w+)", text)
        return m.group(1) if m else None

    def expr_type(self, expr: str, text: str, recv) -> str | None:
        m = re.search(r"handler\.(New\w+)\s*\(", expr)
        if m:
            return self.ctor_type.get(m.group(1), m.group(1)[3:])
        b = re.match(r"(\w+)", expr)
        if not b:
            return None
        if recv and b.group(1) == recv[0]:
            return recv[1]
        return self.var_type(b.group(1), text)

    def chain_roles(self, chain: str, text: str, depth: int = 0) -> list[str]:
        roles = roles_in(chain, self.role_vars)
        base = re.match(r"\s*(\w+)", chain)
        if base and base.group(1) != "r" and depth < 4:
            d = re.search(rf"\b{re.escape(base.group(1))}\s*:?=\s*", text)
            if d:
                roles = self.chain_roles(statement_from(text, d.end()), text, depth + 1) + roles
        return roles

    def parse_routes(self, typ: str, prefix: str, roles: list[str], depth: int) -> None:
        f = self.method_file.get((typ, "Routes"))
        if not f:
            return
        text = read(f)
        m = re.search(rf"func\s*\(\s*(\w+)\s+\*?{re.escape(typ)}\s*\)\s*Routes\s*\(\s*\)[^{{]*\{{", text)
        if not m:
            return
        body_open = m.end() - 1
        self.parse_block(text, f, body_open + 1, match_forward(text, body_open), prefix, roles,
                         (m.group(1), typ), depth)

    def parse_block(self, text, file, start, end, prefix, roles, recv, depth) -> None:
        if depth > 6:
            return
        pos = start
        use_roles: list[str] = []
        for m in CHI_CALL_RE.finditer(text, start, end):
            if m.start() < pos:
                continue
            kind = m.group(1)
            open_i = m.end() - 1
            close_i = match_forward(text, open_i)
            args = text[open_i + 1:close_i]
            pos = close_i
            here = roles + use_roles + self.chain_roles(text[chain_start(text, m.start()):m.start()], text)
            if kind == "Use":
                use_roles += roles_in(args, self.role_vars)
                continue
            a = args.lstrip()
            lit = STR_RE.match(a)
            path = lit.group(1) if lit else None
            if kind in ("Route", "Group"):
                fpos = text.find("func", open_i, close_i)
                if fpos < 0:
                    continue
                fp = text.find("(", fpos)
                body_open = text.find("{", match_forward(text, fp), close_i)
                if body_open < 0:
                    continue
                sub = join_path(prefix, path) if kind == "Route" and path else prefix
                self.parse_block(text, file, body_open + 1, match_forward(text, body_open), sub, here,
                                 recv, depth + 1)
                continue
            if not path or not path.startswith("/"):
                continue
            rest = a[lit.end():].lstrip().removeprefix(",").strip()
            full = join_path(prefix, path)
            if kind == "Mount":
                typ = self.expr_type(rest, text, recv)
                if typ:
                    self.parse_routes(typ, full, here, depth + 1)
                continue
            handler, files = "", {file}
            hm = re.fullmatch(r"(\w+)\.(\w+)", rest)
            if hm:
                typ = recv[1] if recv and hm.group(1) == recv[0] else self.var_type(hm.group(1), text)
                if typ:
                    handler = f"{typ}.{hm.group(2)}"
                    mf = self.method_file.get((typ, hm.group(2)))
                    if mf:
                        files.add(mf)
            self.endpoints.append(Endpoint(self.name, kind.upper(), full, dedupe(here), handler, files))


