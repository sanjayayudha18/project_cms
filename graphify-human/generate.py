def load_known_tables() -> set[str]:
    names: set[str] = set()
    for p in sorted((ROOT / MIGRATIONS_DIR).glob("*.sql")):
        text = p.read_text(encoding="utf-8", errors="replace")
        names |= {m.group(1).lower() for m in re.finditer(
            r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:public\.)?\"?(\w+)", text, re.I)}
    return names


SQL_REF = r"\b(INSERT\s+INTO|DELETE\s+FROM|UPDATE|FROM|JOIN)\s+(?:ONLY\s+)?(?:public\.)?\"?(\w+)"
SQL_REF_CI = re.compile(SQL_REF, re.I)
SQL_REF_CS = re.compile(SQL_REF)  # code files: uppercase keywords only, skips English prose


def table_refs(text: str, known: set[str], case_insensitive: bool):
    for m in (SQL_REF_CI if case_insensitive else SQL_REF_CS).finditer(text):
        name = m.group(2).lower()
        if name in known:
            yield name, m.group(1).split()[0].upper() in ("INSERT", "DELETE", "UPDATE")


def load_sqlc_queries(known: set[str]) -> dict[str, list[tuple[str, set[tuple[str, bool]]]]]:
    """sqlc query name -> [(file, {(table, is_write)})]."""
    out: dict[str, list] = defaultdict(list)
    for d in SQLC_QUERY_DIRS:
        for f in files_under(d, ".sql"):
            text = read(f)
            heads = list(re.finditer(r"--\s*name:\s*(\w+)", text))
            for i, h in enumerate(heads):
                body = text[h.end():heads[i + 1].start() if i + 1 < len(heads) else len(text)]
                body = re.sub(r"--[^\n]*", "", body)
                out[h.group(1)].append((f, set(table_refs(body, known, True))))
    return out


@dataclass
class TableUse:
    read: bool = False
    write: bool = False
    sources: set[str] = field(default_factory=set)


def feature_tables(feat: Feature, known: set[str], sqlc) -> dict[str, TableUse]:
    tables: dict[str, TableUse] = defaultdict(TableUse)

    def note(name: str, is_write: bool, source: str):
        t = tables[name]
        t.write |= is_write
        t.read |= not is_write
        t.sources.add(source)

    for f in sorted(feat.files):
        if f.endswith(".sql"):
            text = re.sub(r"--[^\n]*", "", read(f))
            for name, w in table_refs(text, known, True):
                note(name, w, f)
        elif f.endswith((".go", ".py")):
            text = read(f)
            for name, w in table_refs(text, known, False):
                note(name, w, f)
            if f.endswith(".go"):
                for q in sorted(set(re.findall(r"\.(\w+)\(", text)) & sqlc.keys()):
                    for qfile, refs in sqlc[q]:
                        for name, w in refs:
                            note(name, w, qfile)
    return dict(sorted(tables.items()))


