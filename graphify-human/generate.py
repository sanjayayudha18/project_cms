@dataclass
class Feature:
    id: str
    label: str
    status: str
    summary: str
    dev_plan: str
    portal: list[str]
    globs: list[str]
    mock_globs: list[str]
    related: list[str]
    docs: list[str]
    files: set[str] = field(default_factory=set)
    mock_files: set[str] = field(default_factory=set)
    warnings: list[str] = field(default_factory=list)


def load_config(path: Path) -> tuple[list[str], list[Feature], list[str]]:
    with path.open("rb") as fh:
        raw = tomllib.load(fh)
    excludes = list(raw.get("exclude", {}).get("globs", []))
    errors: list[str] = []
    features: list[Feature] = []
    seen: set[str] = set()
    for i, f in enumerate(raw.get("feature", []), start=1):
        where = f"[[feature]] ke-{i} ({f.get('id', '?')})"
        missing = [k for k in REQUIRED_KEYS if k not in f]
        if missing:
            errors.append(f"{where}: field wajib hilang: {', '.join(missing)}")
            continue
        if f["status"] not in STATUS_LABEL:
            errors.append(f"{where}: status '{f['status']}' tidak valid (pilih: {', '.join(STATUS_LABEL)})")
        if f["id"] in seen:
            errors.append(f"{where}: id duplikat")
        seen.add(f["id"])
        features.append(Feature(
            id=f["id"],
            label=f["label"],
            status=f["status"],
            summary=" ".join(f.get("summary", "").split()),
            dev_plan=str(f.get("dev_plan", "")),
            portal=list(f.get("portal", [])),
            globs=list(f["files"]),
            mock_globs=list(f.get("mock_files", [])),
            related=list(f.get("related", [])),
            docs=list(f.get("docs", [])),
        ))
    if not features and not errors:
        errors.append("features.toml tidak punya [[feature]]")
    return excludes, features, errors


def is_excluded(rel: str, excludes: list[str]) -> bool:
    p = PurePosixPath(rel)
    return any(p.full_match(g) for g in excludes)


def resolve_globs(globs: list[str], excludes: list[str], warnings: list[str], key: str) -> set[str]:
    out: set[str] = set()
    for g in globs:
        hits = [p for p in ROOT.glob(g) if p.is_file()]
        if not hits:
            warnings.append(f"glob `{g}` di `{key}` tidak cocok dengan file apa pun")
        out |= {r for r in map(rel_of, hits) if not is_excluded(r, excludes)}
    return out


# ─── Go: role lists ──────────────────────────────────────────────────────────


def load_go_role_vars() -> dict[str, list[str]]:
    """name -> roles, from `X = []string{...}` lists and string consts in Go code."""
    consts: dict[str, str] = {}
    lists: dict[str, str] = {}
    for d in GO_ROLE_DIRS:
        for f in files_under(d, ".go"):
            text = read(f)
            for m in re.finditer(r"\b(\w+)\s*(?:string\s*)?=\s*\"([^\"]*)\"", text):
                consts.setdefault(m.group(1), m.group(2))
            for m in re.finditer(r"\b(\w+)\s*=\s*\[\]string\s*\{([^}]*)\}", text):
                lists.setdefault(m.group(1), m.group(2))
    out: dict[str, list[str]] = {}
    for name, body in lists.items():
        body = re.sub(r"//[^\n]*", "", body)
        roles = []
        for tok in re.findall(r'"[^"]*"|[\w.]+', body):
            if tok.startswith('"'):
                roles.append(tok.strip('"'))
            else:
                roles.append(consts.get(tok.rsplit(".", 1)[-1], f"?{tok}"))
        out[name] = roles
    return out


def roles_in(fragment: str, role_vars: dict[str, list[str]]) -> list[str]:
    roles: list[str] = []
    for m in re.finditer(r"RequireRoles\(", fragment):
        close = match_forward(fragment, m.end() - 1)
        args = fragment[m.end():close]
        roles += STR_RE.findall(args)
        for v in re.findall(r"([\w.]+)\s*\.\.\.", args):
            roles += role_vars.get(v.rsplit(".", 1)[-1], [f"?{v}"])
    return roles


