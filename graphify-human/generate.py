# ─── Small helpers ───────────────────────────────────────────────────────────


@cache
def read(rel: str) -> str:
    try:
        return (ROOT / rel).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def rel_of(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def files_under(dir_rel: str, suffix: str) -> list[str]:
    d = ROOT / dir_rel
    if not d.is_dir():
        return []
    return sorted(rel_of(p) for p in d.rglob(f"*{suffix}") if not p.name.endswith("_test.go"))


def dedupe(items):
    return list(dict.fromkeys(items))


def line_of(text: str, pos: int) -> int:
    return text.count("\n", 0, pos) + 1


def join_path(prefix: str, path: str) -> str:
    if path in ("", "/"):
        return prefix or "/"
    return prefix.rstrip("/") + "/" + path.lstrip("/")


def norm_path(p: str) -> str:
    """Path key for matching frontend calls to backend routes: params become {}."""
    p = re.sub(r"\{[^}]*\}", "{}", p)
    p = re.sub(r"/\*$", "", p)
    return p.rstrip("/") or "/"


def match_forward(text: str, i: int) -> int:
    """Index of the bracket closing the one at text[i]. Skips strings and comments."""
    depth, n, quote = 0, len(text), None
    while i < n:
        c = text[i]
        if quote:
            if c == "\\" and quote != "`":
                i += 2
                continue
            if c == quote:
                quote = None
        elif text.startswith("//", i):
            nl = text.find("\n", i)
            i = n if nl < 0 else nl
            continue
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            i = n if end < 0 else end + 2
            continue
        elif c in "\"'`":
            quote = c
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return n - 1


def match_back(text: str, i: int) -> int:
    """Index of the bracket opening the one closed at text[i] (naive string skip)."""
    depth = 0
    while i >= 0:
        c = text[i]
        if c == '"':
            i = text.rfind('"', 0, i)
            if i < 0:
                return 0
        elif c in ")]}":
            depth += 1
        elif c in "([{":
            depth -= 1
            if depth == 0:
                return i
        i -= 1
    return 0


def skip_ws_back(text: str, i: int) -> int:
    while i >= 0 and text[i] in " \t\r\n":
        i -= 1
    return i


def chain_start(text: str, dot: int) -> int:
    """Start of the receiver chain ending right before text[dot] ('.Mount(' etc.)."""
    i, start = dot - 1, dot
    while True:
        i = skip_ws_back(text, i)
        if i < 0:
            break
        c = text[i]
        if c in ")]":
            i = match_back(text, i) - 1
            start = i + 1
            continue
        if c.isalnum() or c == "_":
            j = i
            while j >= 0 and (text[j].isalnum() or text[j] == "_"):
                j -= 1
            start = j + 1
            k = skip_ws_back(text, j)
            if k >= 0 and text[k] == ".":
                i = k - 1
                continue
        break
    return start


def statement_from(text: str, i: int) -> str:
    """Text from i to the end of the Go statement (newline at bracket depth 0)."""
    depth, j, n = 0, i, len(text)
    while j < n:
        c = text[j]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "\n" and depth <= 0 and not text[i:j].rstrip().endswith((".", ",", "(")):
            break
        j += 1
    return text[i:j]


