class RouteMatcher:
    """Maps a frontend call to backend endpoint keys. A `{}` segment on either side is a wildcard,
    so `${BASE}/${vendorId}/${kind}` matches every `/admin/vendors/{vendorID}/<child>` route."""

    def __init__(self, endpoints: list[Endpoint]):
        self.keys = {e.key for e in endpoints}
        self.by_shape: dict[tuple[str, int], list[tuple[tuple[str, str], list[str]]]] = defaultdict(list)
        for key in self.keys:
            segs = key[1].split("/")
            self.by_shape[(key[0], len(segs))].append((key, segs))

    def match(self, call: FeCall) -> list[tuple[str, str]]:
        if not call.resolved:
            return []
        if call.key in self.keys:
            return [call.key]
        segs = call.key[1].split("/")
        return sorted(
            key for key, be in self.by_shape.get((call.method, len(segs)), [])
            if all(a == b or "{}" in (a, b) for a, b in zip(segs, be, strict=True))
        )


def build_context(feat, all_endpoints, matcher, known, sqlc, nav, graph, excludes, by_id, owners):
    warnings: list[str] = []
    calls = [c for f in sorted(feat.files) if f.endswith((".ts", ".tsx")) and f.startswith("frontend/")
             for c in fe_calls(f)]
    callers: dict[tuple[str, str], list[FeCall]] = defaultdict(list)
    unmatched = []
    for c in calls:
        keys = matcher.match(c)
        for k in keys:
            callers[k].append(c)
        if not keys:
            unmatched.append(c)

    eps = [e for e in all_endpoints if e.files & feat.files or e.key in callers]
    eps = sorted({(e.module, e.method, e.path): e for e in eps}.values(), key=lambda e: (e.path, e.method))

    routes = [r for f in sorted(feat.files) for r in fe_routes(f)]
    cp_paths = {r.path for r in routes if r.file.startswith("frontend/CompanyPortal-Vite/")}
    nav_items = [n for n in nav if n.href in cp_paths]

    py_eps = [p for f in sorted(feat.files) if f.startswith("backend_python/") and f.endswith(".py")
              for p in py_endpoints(f)]

    missing_mock = feat.mock_files - feat.files
    for m in sorted(missing_mock):
        warnings.append(f"mock file `{m}` tidak termasuk `files` (atau terkena exclude)")

    return {
        "endpoints": eps,
        "callers": callers,
        "unmatched": unmatched,
        "routes": routes,
        "nav": nav_items,
        "py_endpoints": py_eps,
        "tables": feature_tables(feat, known, sqlc),
        "related": related_files(feat, graph, excludes) if graph else None,
        "by_id": by_id,
        "owners": owners,
        "warnings": warnings,
    }


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description="Generate the human-readable CMS feature map.")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output folder (default: graphify-human/out)")
    args = ap.parse_args()
    out_dir = args.out.resolve()

    excludes, features, errors = load_config(CONFIG)
    if errors:
        print("features.toml tidak valid:")
        for e in errors:
            print(f"  - {e}")
        return 1

    for f in features:
        f.files = resolve_globs(f.globs, excludes, f.warnings, "files")
        f.mock_files = resolve_globs(f.mock_globs, excludes, f.warnings, "mock_files")

    role_vars = load_go_role_vars()
    endpoints: list[Endpoint] = []
    for name, main_rel, handler_dir in GO_MODULES:
        endpoints += GoModule(name, main_rel, handler_dir, role_vars).parse()
    matcher = RouteMatcher(endpoints)

    known = load_known_tables()
    sqlc = load_sqlc_queries(known)
    nav = load_nav()
    graph = load_graph()
    head = git("rev-parse", "HEAD")

    graph_note = ""
    if graph is None:
        graph_note = "graph.json tidak ada; bagian 'File terkait' kosong. Jalankan `graphify update .`."
    elif head and graph.commit and graph.commit != head:
        # The graph folder is committed, so built_at_commit always trails HEAD. Only code changes count.
        changed = [p for p in git("diff", "--name-only", graph.commit, "HEAD").splitlines()
                   if p.endswith(CODE_SUFFIXES) and not is_excluded(p, excludes)]
        if changed:
            graph_note = (f"{len(changed)} file kode berubah sejak graph dibangun. "
                          "Jalankan `graphify update .` dari root repo supaya 'File terkait' akurat.")

    by_id = {f.id: f for f in features}
    owners: dict[str, list[str]] = defaultdict(list)
    for f in features:
        for path in f.files:
            owners[path].append(f.id)

    contexts = {f.id: build_context(f, endpoints, matcher, known, sqlc, nav, graph, excludes, by_id, owners)
                for f in features}

    out_dir.mkdir(parents=True, exist_ok=True)
    renderer = Renderer(out_dir)
    written = {"index.md"}
    (out_dir / "index.md").write_text(
        renderer.index(features, contexts, {"head": head, "graph_commit": graph.commit if graph else "",
                                            "graph_note": graph_note}), encoding="utf-8")
    for f in features:
        (out_dir / f"{f.id}.md").write_text(renderer.feature(f, contexts[f.id]), encoding="utf-8")
        written.add(f"{f.id}.md")
    # Drop pages of features removed from features.toml (only files this script generated).
    for stale in out_dir.glob("*.md"):
        if stale.name not in written and stale.read_text(encoding="utf-8", errors="replace").startswith(MARKER):
            stale.unlink()

    print(f"Peta fitur ditulis ke {out_dir}")
    print(f"  endpoint Go terbaca: {len(endpoints)}, tabel dikenal: {len(known)}, menu: {len(nav)}")
    if graph_note:
        print(f"  catatan: {graph_note}")
    for f in features:
        c = contexts[f.id]
        warn = len(f.warnings) + len(c["warnings"])
        print(f"  - {f.id}: {len(f.files)} file, {len(c['endpoints'])} endpoint, "
              f"{len(c['tables'])} tabel, {warn} peringatan")
    return 0


if __name__ == "__main__":
    sys.exit(main())
