@dataclass
class Graph:
    commit: str
    # file -> {other_file: [uses_count, used_by_count]}
    deps: dict[str, dict[str, list[int]]]


def load_graph() -> Graph | None:
    if not GRAPH.is_file():
        return None
    data = json.loads(GRAPH.read_text(encoding="utf-8"))
    node_file: dict[str, str] = {}
    for n in data.get("nodes", []):
        sf = n.get("source_file")
        if not sf or n.get("file_type") != "code":
            continue
        sf = sf.replace("\\", "/")
        if os.path.isabs(sf):
            try:
                sf = Path(sf).resolve().relative_to(ROOT).as_posix()
            except ValueError:
                continue
        node_file[n["id"]] = sf
    deps: dict[str, dict[str, list[int]]] = defaultdict(lambda: defaultdict(lambda: [0, 0]))
    for link in data.get("links", []):
        if link.get("relation") not in DEP_RELATIONS:
            continue
        a, b = node_file.get(link.get("source")), node_file.get(link.get("target"))
        if not a or not b or a == b:
            continue
        deps[a][b][0] += 1  # a uses b
        deps[b][a][1] += 1  # b is used by a
    return Graph(str(data.get("built_at_commit", "")), deps)


def related_files(feat: Feature, graph: Graph, excludes: list[str]) -> list[tuple[str, int, int]]:
    tally: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for f in feat.files:
        for other, (uses, used_by) in graph.deps.get(f, {}).items():
            if other in feat.files or is_excluded(other, excludes) or other.startswith("graphify-out/"):
                continue
            tally[other][0] += uses
            tally[other][1] += used_by
    rows = [(f, u, b) for f, (u, b) in tally.items() if (ROOT / f).is_file()]
    rows.sort(key=lambda r: (-(r[1] + r[2]), r[0]))
    return rows[:RELATED_LIMIT]


# ─── Git ─────────────────────────────────────────────────────────────────────


def git(*args: str) -> str:
    try:
        r = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return ""
    return r.stdout.strip() if r.returncode == 0 else ""


