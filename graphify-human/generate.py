@dataclass
class PyEndpoint:
    service: str
    method: str
    path: str
    deps: list[str]
    file: str
    line: int


def py_endpoints(rel: str) -> list[PyEndpoint]:
    text = read(rel)
    prefix, deps = "", []
    m = re.search(r"APIRouter\(", text)
    if m:
        decl = text[m.end():match_forward(text, m.end() - 1)]
        p = re.search(r"prefix\s*=\s*[\"']([^\"']*)", decl)
        prefix = p.group(1) if p else ""
        deps = re.findall(r"Depends\((\w+)\)", decl)
    service = rel.split("/")[1] if rel.count("/") >= 2 else rel
    return [
        PyEndpoint(service, r.group(2).upper(), join_path(prefix, r.group(3)), deps, rel, line_of(text, r.start()))
        for r in re.finditer(r"@(\w+)\.(get|post|put|patch|delete)\(\s*[\"']([^\"']*)[\"']", text)
    ]


# ─── Frontend: API calls, routes, navigation ─────────────────────────────────


@dataclass
class FeCall:
    method: str
    path: str
    resolved: bool
    file: str
    line: int

    @property
    def key(self) -> tuple[str, str]:
        return self.method, norm_path(self.path)


def read_literal(text: str, i: int):
    """Parts of the JS string/template literal at text[i]: [("s", text) | ("x", expr)]."""
    q = text[i] if i < len(text) else ""
    if q in "\"'":
        j = i + 1
        while j < len(text) and text[j] != q:
            j += 2 if text[j] == "\\" else 1
        return [("s", text[i + 1:j])]
    if q != "`":
        return None
    parts, buf, j = [], [], i + 1
    while j < len(text):
        c = text[j]
        if c == "`":
            break
        if text.startswith("${", j):
            if buf:
                parts.append(("s", "".join(buf)))
                buf = []
            k = match_forward(text, j + 1)
            parts.append(("x", text[j + 2:k]))
            j = k + 1
            continue
        buf.append(c)
        j += 1
    if buf:
        parts.append(("s", "".join(buf)))
    return parts


def fe_path(parts, consts: dict[str, str], fns: dict[str, str]) -> tuple[str, bool]:
    out = ""
    for kind, val in parts:
        if kind == "s":
            out += val
            continue
        expr = val.strip()
        call = re.match(r"(\w+)\s*\(", expr)
        if expr in consts:
            out += consts[expr]
        elif call and call.group(1) in fns:
            out += fns[call.group(1)]
        elif not out:
            return f"${{{expr}}}", False  # path held in a local variable
        elif out.endswith("/"):
            out += "{p}"
        else:
            out += "?"  # query suffix such as ${qs ? `?${qs}` : ""}
    out = re.sub(r"\$\{[^}]*\}", "{p}", out).split("?", 1)[0]
    if not out.startswith("/"):
        return out or "?", False
    if not out.startswith("/api"):
        out = "/api/v1" + out  # CompanyPortal client prefixes apiConfig.baseURL
    return out, True


FE_VERB_RE = re.compile(r"\bapi\.(get|post|put|patch|delete)\b")
FE_CLIENT_RE = re.compile(r"method:\s*[\"'](GET|POST|PUT|PATCH|DELETE)[\"'][^}]{0,200}?\bpath:\s*", re.S)


def fe_calls(rel: str) -> list[FeCall]:
    text = read(rel)
    consts = {m.group(1): m.group(3) for m in re.finditer(r"\bconst\s+(\w+)\s*=\s*([\"'`])([^\"'`]*)\2", text)}
    fns = {m.group(1): m.group(2) for m in re.finditer(r"\bconst\s+(\w+)\s*=\s*\([^)]*\)\s*=>\s*`([^`]*)`", text)}
    calls = []

    def add(method: str, lit_at: int, pos: int):
        parts = read_literal(text, lit_at)
        if parts is None:  # bare expression: BASE, base(vendorId), url
            ident = re.match(r"[\w.]+(?:\([^)]*\))?", text[lit_at:])
            if not ident:
                return
            parts = [("x", ident.group(0))]
        path, ok = fe_path(parts, consts, fns)
        calls.append(FeCall(method, path, ok, rel, line_of(text, pos)))

    for m in FE_VERB_RE.finditer(text):
        paren = text.find("(", m.end())
        if paren < 0 or text[m.end():paren].strip()[:1] not in ("", "<"):
            continue
        j = paren + 1
        while j < len(text) and text[j] in " \t\r\n":
            j += 1
        add(m.group(1).upper(), j, m.start())
    for m in FE_CLIENT_RE.finditer(text):
        add(m.group(1), m.end(), m.start())
    return calls


@dataclass
class FeRoute:
    path: str
    roles: list[str] | None
    file: str


def fe_routes(rel: str) -> list[FeRoute]:
    if "/src/routes/" not in rel:
        return []
    text = read(rel)
    guard = re.search(r"requireRoles\(\s*\[([^\]]*)\]", text)
    roles = STR_RE.findall(guard.group(1)) if guard else None
    return [FeRoute(m.group(1), roles, rel) for m in re.finditer(r"\bpath:\s*[\"']([^\"']+)[\"']", text)]


@dataclass
class NavItem:
    label: str
    href: str
    roles: list[str]
    disabled: bool


def load_nav() -> list[NavItem]:
    text = read(NAV_FILE)
    labels = list(re.finditer(r"\blabel:\s*\"([^\"]+)\"", text))
    items = []
    for i, m in enumerate(labels):
        end = labels[i + 1].start() if i + 1 < len(labels) else len(text)
        chunk = text[m.end():end]
        href = re.search(r"\bhref:\s*\"([^\"]+)\"", chunk)
        roles_m = re.search(r"\broles:\s*\[", chunk)
        if not href or not roles_m:
            continue
        body = chunk[roles_m.end():match_forward(chunk, roles_m.end() - 1)]
        roles = STR_RE.findall(body) + [f"...{s}" for s in re.findall(r"\.\.\.\s*(\w+)", body)]
        items.append(NavItem(m.group(1), href.group(1), roles, bool(re.search(r"\bdisabled:\s*true", chunk))))
    return items


