def area_of(path: str) -> str:
    for prefix, name in (
        ("frontend/CompanyPortal-Vite/", "Frontend CompanyPortal"),
        ("frontend/VendorPortal-Vite/", "Frontend VendorPortal"),
        ("backend/queries/", "SQL query (backend)"),
        ("backend-exq/queries/", "SQL query (backend-exq)"),
        ("backend/", "Backend Go ATM (:8080)"),
        ("backend-exq/", "Backend Go EXQ (:8081)"),
        ("backend_python/", "Python ETL / EOD"),
        ("pkg/", "pkg (shared Go)"),
    ):
        if path.startswith(prefix):
            return name
    return "Lainnya"


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def fmt_roles(roles: list[str] | None) -> str:
    if not roles:
        return "_tanpa role guard_"
    return ", ".join(f"`{r[1:]}` (tidak terbaca)" if r.startswith("?") else r for r in dedupe(roles))


class Renderer:
    def __init__(self, out_dir: Path):
        self.out_dir = out_dir

    def link(self, rel: str, text: str | None = None) -> str:
        href = Path(os.path.relpath(ROOT / rel, self.out_dir)).as_posix().replace(" ", "%20")
        return f"[`{text or rel}`]({href})"

    def file_line(self, rel: str, line: int) -> str:
        return self.link(rel, f"{Path(rel).name}:{line}")

    def feature(self, feat, ctx) -> str:
        L: list[str] = [MARKER, f"# {feat.label}", ""]
        L += ["> Dibuat otomatis dari `graphify-human/features.toml`. Jangan edit file ini:",
              "> ubah `features.toml`, lalu jalankan `py graphify-human/generate.py`.", ""]
        L += ["| | |", "| --- | --- |",
              f"| ID | `{feat.id}` |",
              f"| Status | {STATUS_LABEL[feat.status]} |",
              f"| Portal | {', '.join(feat.portal) or '-'} |",
              f"| Development plan | {cell(feat.dev_plan) or '-'} |",
              f"| File inti | {len(feat.files)} |", ""]
        if feat.summary:
            L += ["## Ringkasan", "", feat.summary, ""]

        L += self.roles_section(ctx)
        L += self.endpoint_section(ctx)
        L += self.table_section(ctx["tables"])
        L += self.core_files_section(feat)
        L += self.related_section(ctx)
        L += self.links_section(feat, ctx)

        warnings = feat.warnings + ctx["warnings"]
        if warnings:
            L += ["## Peringatan", ""] + [f"- {w}" for w in warnings] + [""]
        return "\n".join(L).rstrip() + "\n"

    def roles_section(self, ctx) -> list[str]:
        L = ["## Peran (role)", ""]
        if ctx["nav"]:
            L += ["Menu sidebar CompanyPortal (`navigation.ts`):", ""]
            for n in ctx["nav"]:
                flag = " (disabled)" if n.disabled else ""
                L.append(f"- **{n.label}**{flag} `{n.href}`: {fmt_roles(n.roles)}")
            L.append("")
        if ctx["routes"]:
            L += ["Route frontend:", ""]
            for r in ctx["routes"]:
                L.append(f"- `{r.path}`: {fmt_roles(r.roles)} ({self.link(r.file, Path(r.file).name)})")
            L.append("")
        be_roles = dedupe(r for e in ctx["endpoints"] for r in e.roles)
        if be_roles:
            L += [f"Gabungan role di endpoint backend: {fmt_roles(be_roles)}", ""]
        if len(L) == 2:
            L += ["_Tidak ada role guard yang terdeteksi._", ""]
        return L

    def endpoint_section(self, ctx) -> list[str]:
        L = ["## Endpoint backend", ""]
        eps = ctx["endpoints"]
        if eps:
            L += ["| Method | Path | Role | Handler | Dipanggil dari frontend |", "| --- | --- | --- | --- | --- |"]
            for e in eps:
                callers = ctx["callers"].get(e.key, [])
                caller_txt = "<br>".join(dedupe(self.file_line(c.file, c.line) for c in callers)) or "-"
                handler_file = next((f for f in sorted(e.files) if "/handler/" in f), "")
                handler = self.link(handler_file, e.handler) if e.handler and handler_file else (e.handler or "-")
                mod = "" if e.module == "backend" else f" _({e.module})_"
                roles = cell(fmt_roles(e.roles))
                L.append(f"| {e.method} | `{cell(e.path)}`{mod} | {roles} | {handler} | {caller_txt} |")
            L.append("")
        else:
            L += ["_Tidak ada endpoint Go yang terdeteksi untuk file fitur ini._", ""]
        if ctx["py_endpoints"]:
            L += ["Endpoint Python (FastAPI, dipanggil backend Go / proxy, bukan langsung dari browser):", "",
                  "| Service | Method | Path | Dependency | File |", "| --- | --- | --- | --- | --- |"]
            for p in ctx["py_endpoints"]:
                deps = ", ".join(f"`{d}`" for d in p.deps) or "-"
                L.append(f"| {p.service} | {p.method} | `{cell(p.path)}` | {deps} | {self.file_line(p.file, p.line)} |")
            L.append("")
        if ctx["unmatched"]:
            L += ["Panggilan API frontend yang tidak cocok dengan endpoint Go mana pun "
                  "(bisa proxy ke Python, path dinamis, atau endpoint hilang):", ""]
            for c in ctx["unmatched"]:
                tag = "" if c.resolved else " (path tidak bisa dibaca statis)"
                L.append(f"- {c.method} `{c.path}`{tag} ({self.file_line(c.file, c.line)})")
            L.append("")
        return L

    def table_section(self, tables: dict[str, TableUse]) -> list[str]:
        L = ["## Tabel database", ""]
        if not tables:
            return L + ["_Tidak ada tabel yang terdeteksi._", ""]
        L += ["| Tabel | Baca | Tulis | Ditemukan di |", "| --- | --- | --- | --- |"]
        for name, t in tables.items():
            src = ", ".join(self.link(s, Path(s).name) for s in sorted(t.sources))
            L.append(f"| `{name}` | {'ya' if t.read else '-'} | {'ya' if t.write else '-'} | {src} |")
        return L + ["", "_Baca/tulis dideteksi dari kata kunci SQL (FROM/JOIN vs INSERT/UPDATE/DELETE), "
                        "termasuk query sqlc yang dipanggil dari file Go fitur ini._", ""]

    def core_files_section(self, feat: Feature) -> list[str]:
        L = [f"## File inti ({len(feat.files)})", ""]
        by_area: dict[str, list[str]] = defaultdict(list)
        for f in sorted(feat.files):
            by_area[area_of(f)].append(f)
        for area in sorted(by_area):
            L += [f"**{area}**", ""]
            for f in by_area[area]:
                L.append(f"- {self.link(f)}{' **(mock)**' if f in feat.mock_files else ''}")
            L.append("")
        return L

    def related_section(self, ctx) -> list[str]:
        L = ["## File terkait (dari graph)", ""]
        rows = ctx["related"]
        if rows is None:
            return L + ["_`graphify-out/graph.json` tidak ada. Jalankan `graphify update .`._", ""]
        if not rows:
            return L + ["_Tidak ada dependensi ke file di luar file inti._", ""]
        L += ["| File | Dipakai fitur | Memakai fitur | Milik fitur |", "| --- | --- | --- | --- |"]
        for f, uses, used_by in rows:
            owners = ", ".join(f"`{o}`" for o in ctx["owners"].get(f, [])) or "-"
            L.append(f"| {self.link(f)} | {uses or '-'} | {used_by or '-'} | {owners} |")
        note = f"_Angka = jumlah relasi di graph (impor, panggilan, referensi). Maksimal {RELATED_LIMIT} baris._"
        return L + ["", note, ""]

    def links_section(self, feat: Feature, ctx) -> list[str]:
        L = []
        if feat.related:
            L += ["## Fitur terkait", ""]
            for r in feat.related:
                other = ctx["by_id"].get(r)
                L.append(f"- [{other.label}]({r}.md)" if other else f"- `{r}` (belum dipetakan di features.toml)")
            L.append("")
        if feat.docs:
            L += ["## Dokumen", ""]
            for d in feat.docs:
                exists = (ROOT / d).exists()
                L.append(f"- {self.link(d)}" if exists else f"- `{d}` (tidak ditemukan)")
            L.append("")
        return L

    def index(self, features, contexts, meta) -> str:
        L = [MARKER, "# Peta fitur CMS (graphify-human)", "",
             "> Dibuat otomatis dari `graphify-human/features.toml`. Jangan edit file ini:",
             "> ubah `features.toml`, lalu jalankan `py graphify-human/generate.py`.", "",
             f"- Commit kode: `{meta['head'][:10] or '?'}`",
             f"- Graph dibangun di commit: `{meta['graph_commit'][:10] or '?'}`"]
        if meta["graph_note"]:
            L.append(f"- {meta['graph_note']}")
        L += ["", "| Fitur | Status | Portal | Dev plan | File inti | Endpoint | Tabel |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
        for f in features:
            c = contexts[f.id]
            L.append(f"| [{cell(f.label)}]({f.id}.md) | {STATUS_LABEL[f.status]} | {', '.join(f.portal) or '-'} | "
                     f"{cell(f.dev_plan) or '-'} | {len(f.files)} | {len(c['endpoints'])} | {len(c['tables'])} |")
        warn_count = sum(len(f.warnings) + len(contexts[f.id]["warnings"]) for f in features)
        if warn_count:
            L += ["", f"Ada {warn_count} peringatan di halaman fitur (bagian **Peringatan**)."]
        return "\n".join(L) + "\n"


